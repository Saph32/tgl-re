#!/usr/bin/env python3
"""Turn the code trace into `annotations/regions/20-traced.json`.

    python tools/gen-code-regions.py            # rewrite the file
    python tools/gen-code-regions.py --check    # report what would change, write nothing

**The output file is generated. A hand edit to it is lost on the next run.** To say more
about a stretch than the trace can, claim it in a hand-authored region file: this generator
loads the annotation store with its own previous output excluded and then subtracts
everything else that is already claimed, so a hand-written region always wins and the
traced region shrinks around it.

Two things are emitted, and they are different kinds of claim:

* **code** - contiguous runs of bytes the trace reached by following control flow. The
  extent is evidence; what the code *does* is not claimed at all, and the description says
  so. These regions are where a bank's coverage comes from.
* **data** - the inline argument blocks that follow a registered inline-argument call.
  These are bytes the trace stepped over rather than bytes it reached, and the evidence for
  each is the callee's own arithmetic: $D5CC advances its pointer by a constant 4, so the
  four bytes after each of its call sites are its argument and nothing else.

The check that matters here is not coverage. It is that **every code region begins at a
byte the trace started an instruction at.** Byte-exactness cannot catch a region that
begins one byte early - 6502 has no alignment, so a disassembly from the wrong offset
produces legal instructions and reads perfectly fine - and this is the check that can.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tgl.model import AnnotationError, bank_window, load

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "annotations" / "regions" / "20-traced.json"

# The tracer's filename is not an importable module name, so it is loaded by path rather
# than renamed: the name `trace-code.py` is what the playbook and every other document in
# this project call it, and a second name for one tool is a thing to get wrong later.
_spec = importlib.util.spec_from_file_location(
    "trace_code", Path(__file__).resolve().parent / "trace-code.py")
trace_code = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(trace_code)


CODE_DESC = (
    "A run of {size:,} bytes the code trace reached by following control flow, in bank "
    "{bank} at ${start:04X}-${end:04X}. **This region claims the extent and nothing else.** "
    "What the code does has not been established; the evidence is that every byte here is "
    "part of an instruction on some path the trace could follow from the interrupt vectors "
    "and the banks' entry tables, and that the trace met no illegal opcode anywhere. "
    "Generated by tools/gen-code-regions.py from tools/trace-code.py - see that tool's "
    "--assumptions for what the reachability rests on. To say more about any part of this "
    "stretch, claim it in a hand-authored region file; the generator subtracts what is "
    "already claimed before it emits, so the hand-written region wins."
)

DATA_DESC = (
    "{size} bytes of inline argument data following `JSR ${target:04X}` at "
    "bank {bank} ${site:04X} - {name}. The callee pops its own return address and reads "
    "these bytes through it, so they are data that happens to sit in the instruction "
    "stream, and a trace that decodes them produces nonsense that still looks like code. "
    "The length is not a guess: it is the constant the callee advances its own pointer by. "
    "What the bytes MEAN is not claimed. See annotations/dispatch.json for the routine and "
    "for how the class of these routines was enumerated."
)


STR_DESC = (
    "A queued PPU write item, written inline after `JSR ${target:04X}` at bank {bank} "
    "${site:04X}. {shape} "
    "The block is {size} bytes and the caller resumes immediately after it; the length "
    "comes from the first byte by the rule in $D591 - (byte & $7F) + 3 below $C0, 9 at or "
    "above - and $D5A5 advances the routine's own pointer by exactly that. "
    "{payload}"
    "Characters are ASCII for the letters and space. NOT ESTABLISHED: the glyphs for codes "
    "outside A-Z and space, which only the font can settle - and no font has been found "
    "yet, because CHR is RAM on this cartridge."
)

FAR_DESC = (
    "Three bytes of far-call argument following `JSR $D76F` at bank {bank} ${site:04X} - "
    "bank number, then the target address minus one, little-endian. They select "
    "**bank {to_bank} ${target:04X}**. The stored word is ${stored:04X} rather than "
    "${target:04X} because $D790 pushes these two bytes as a fake return address and lets "
    "RTS add the one back; that is not an inference, it is what the four instructions at "
    "$D799-$D7A4 do. A far call is the one reference in this ROM that no grep for an "
    "operand will ever surface, so the target is recorded here where a reader will find it."
)


def _runs(offsets: set[int], meta: dict) -> list[tuple[int, int]]:
    """Contiguous stretches, split at PRG bank boundaries.

    Splitting at bank edges is not cosmetic: a region straddling two banks would be two
    separate unknowns living at the same CPU addresses, and the model refuses one anyway.
    """
    edges = {meta["prg_offset"] + n * meta["prg_bank_size"]
             for n in range(meta["prg_bank_count"] + 1)}
    out: list[list[int]] = []
    for off in sorted(offsets):
        if out and off == out[-1][1] and off not in edges:
            out[-1][1] = off + 1
        else:
            out.append([off, off + 1])
    return [(a, b) for a, b in out]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report, write nothing")
    args = ap.parse_args()

    try:
        # Excluding our own previous output is what stops the generator seeing its last run
        # as already-claimed ground and emitting nothing at all.
        rm = load(ROOT, exclude={OUT.name})
        trace_code._verify_abi(rm.rom, rm.meta)
    except AnnotationError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    tr = trace_code.Trace(rm)
    tr.run_to_fixpoint()
    meta = rm.meta

    claimed = {o for r in rm.regions for o in range(r["offset"], r["end"])}
    # The inline blocks whose length is established: a far call's three bytes, and the
    # four a $D5CC call consumes. The jump tables are deliberately NOT here - the trace
    # knows where one entry is, not how many entries there are, and claiming the part it
    # walked to would be claiming an extent nothing establishes.
    sized = {"fixed", "farcall", "ppu_string"}
    inline_bytes = {o for d in tr.sites_inline_data if d["kind"] in sized
                    for o in range(d["offset"], d["offset"] + d["size"])}

    code = tr.covered - claimed - inline_bytes
    regions = []

    for start, end in _runs(code, meta):
        # The check byte-exactness cannot do: a code region must begin where the trace
        # began an instruction. A region starting one byte early still reassembles and
        # still disassembles into legal instructions, so nothing else would notice.
        if start not in tr.starts:
            raise AnnotationError(
                f"traced run at 0x{start:05X} does not begin at an instruction start; "
                "this is a bug in the generator, not something to work around")
        rel = start - meta["prg_offset"]
        bank = rel // meta["prg_bank_size"]
        addr = bank_window(meta, bank) + rel % meta["prg_bank_size"]
        regions.append({
            "id": f"bank{bank}.code_{addr:04X}",
            "offset": start,
            "size": end - start,
            "kind": "code",
            "name": f"Traced code at ${addr:04X}",
            "confidence": "confirmed",
            "cpu_addr": addr,
            "sha1": hashlib.sha1(rm.rom[start:end]).hexdigest(),
            "description": CODE_DESC.format(size=end - start, bank=bank, start=addr,
                                            end=addr + (end - start) - 1),
        })

    by_site = {}
    for d in tr.sites_inline_data:
        if d["kind"] not in sized or d["offset"] in claimed:
            continue
        by_site[d["offset"]] = d
    for off, d in sorted(by_site.items()):
        rel = off - meta["prg_offset"]
        bank = rel // meta["prg_bank_size"]
        addr = bank_window(meta, bank) + rel % meta["prg_bank_size"]
        # Reset per block. Leaving this out let `kind` leak from the previous iteration and
        # every far-call argument that happened to follow a readable string was published
        # as kind "text" with a description that said, correctly, that it was three bytes of
        # far-call argument. The description and the kind disagreed and nothing compared
        # them.
        kind = "data"
        if d["kind"] == "ppu_string":
            site = next(c for c in tr.sites_inline
                        if c["bank"] == d["bank"] and c["addr"] == d["addr"] - 3)
            count = d["count"]
            if site["target"] in (0xD576, 0xC06F):
                shape = ("Its shape is [count][ppu_hi][ppu_lo][count characters]: the "
                         f"destination ${rm.rom[off + 1]:02X}{rm.rom[off + 2]:02X} is in the "
                         "block itself.")
                chars = rm.rom[off + 3:off + d["size"]]
            else:
                shape = ("Its shape is [count][count characters]: unlike $D576 this routine "
                         "takes the PPU address from $18/$19 in RAM rather than from the "
                         "stream, which is what makes its block two bytes shorter.")
                chars = rm.rom[off + 1:off + d["size"]]
            printable = sum(1 for c in chars if 32 <= c < 127)
            text = "".join(chr(c) if 32 <= c < 127 else "." for c in chars)
            if chars and printable / len(chars) >= 0.8:
                kind = "text"
                payload = f'It reads "{text}". '
                name = f'"{text}" at ${addr:04X}'
            else:
                kind = "data"
                payload = (f"The {len(chars)} payload bytes are {text!r} read as ASCII, "
                           "which is not text - so they are tile numbers for something "
                           "drawn rather than written, and this region is kind data on "
                           "that ground alone. ")
                name = f"Queued PPU write at ${addr:04X}"
            if count >= 0xC0:
                payload += (f"The count byte is ${count:02X}, at or above $C0, so its length "
                            "is the fixed 9 rather than a character count - the one branch "
                            "of $D591 that does not derive the length from the byte. ")
            description = STR_DESC.format(target=site["target"], bank=bank,
                                          site=d["addr"] - 3, shape=shape,
                                          size=d["size"], payload=payload)
        elif d["kind"] == "farcall":
            call = next(c for c in tr.sites_farcalls
                        if c["bank"] == d["bank"] and c["addr"] == d["addr"] - 3)
            description = FAR_DESC.format(bank=bank, site=d["addr"] - 3,
                                          to_bank=call["to_bank"], target=call["target"],
                                          stored=(call["target"] - 1) & 0xFFFF)
            name = f"Far-call argument at ${addr:04X}"
        else:
            site = next(c for c in tr.sites_inline
                        if c["bank"] == d["bank"] and c["addr"] == d["addr"] - 3)
            entry = (tr.inline.get((None, site["target"]))
                     or tr.inline[(bank, site["target"])])
            description = DATA_DESC.format(size=d["size"], target=site["target"],
                                           bank=bank, site=d["addr"] - 3,
                                           name=entry["name"])
            name = f"Inline argument at ${addr:04X}"
        regions.append({
            "id": f"bank{bank}.inline_{addr:04X}",
            "offset": off,
            "size": d["size"],
            "kind": kind,
            "name": name,
            "confidence": "confirmed",
            "cpu_addr": addr,
            "sha1": hashlib.sha1(rm.rom[off:off + d["size"]]).hexdigest(),
            "description": description,
        })

    regions.sort(key=lambda r: r["offset"])
    doc = {
        "_comment": (
            "GENERATED by tools/gen-code-regions.py from tools/trace-code.py. Do not hand "
            "edit: the next run overwrites this file. To say more about a stretch than the "
            "trace can, claim it in a hand-authored region file - the generator subtracts "
            "everything already claimed before it emits, so a hand-written region always "
            "wins and the traced region shrinks around it."),
        "regions": regions,
    }
    text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"

    covered = sum(r["size"] for r in regions)
    print(f"{len(regions)} regions, {covered:,} bytes "
          f"({100 * covered / meta['prg_size']:.2f}% of PRG)")
    for kind in sorted({r["kind"] for r in regions}):
        rs = [r for r in regions if r["kind"] == kind]
        print(f"  {kind:<5} {sum(r['size'] for r in rs):>6,} bytes in {len(rs):>3} regions")

    if args.check:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        print("no change" if old == text else "WOULD CHANGE")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
