#!/usr/bin/env python3
"""Turn the tile-block chain into `annotations/regions/45-gfx-blocks.json`.

    python tools/gen-gfx-regions.py            # rewrite the file
    python tools/gen-gfx-regions.py --check    # report, write nothing

**The output file is generated. A hand edit to it is lost on the next run.** Like
`gen-code-regions.py`, this loads the annotation store with its own previous output
excluded and skips anything another file already claims, so a hand-written region always
wins - which is how the font block at bank 2 $8BF8 stays described by
`annotations/regions/41-font.json` and is not overwritten with a codec claim it does not
obey.

Two kinds of region come out:

* **pointer_table** - the per-bank block tables. Their extent is not a guess: every
  pointer in them is a block start, and each block's decoded length lands exactly on the
  next pointer.
* **graphics** - one per block, with `codec` set to the toggle-escape RLE. The extent here
  is the strongest kind of evidence this project has for a data region: it is not a
  boundary argument but a chain, where a wrong length for one block derails every block
  after it in the bank.

See `tools/tgl/gfx.py` for the format itself and for what is NOT established.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tgl import gfx
from tgl.model import load

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "annotations" / "regions" / "45-gfx-blocks.json"

BLOCK_DESC = (
    "A tile block, {size} ROM bytes decoding to {out} bytes = {tiles} tiles ({ratio:.2f}x). "
    "The escape byte is ${esc:02X}, taken from the block's own first byte; the second "
    "header byte is ${hdr2:02X} and is NOT understood. Decoding starts in literal mode, the "
    "escape toggles into a run section of [value][count] pairs, the escape toggles back, "
    "and two escape bytes in a row - an empty section - end the block. "
    "THE EXTENT IS CHAINED, NOT ARGUED: this block's decoded length ends exactly where the "
    "next block's pointer says it should, and that holds for every block in the bank in "
    "sequence, so a wrong length here would derail the rest of the bank. "
    "{live}"
    "Generated by tools/gen-gfx-regions.py; the codec and its evidence are in tools/tgl/gfx.py."
)

TABLE_DESC = (
    "{count} little-endian pointers, ${start:04X}-${end:04X}, each naming a tile block in "
    "this bank. Established by the partition test rather than by counting a gap: decoding "
    "the block at each pointer with the toggle-escape codec consumes exactly the bytes up "
    "to the next pointer. Duplicate entries occur and are kept - two ids can share one "
    "graphic. Words of $FFFF and $0000 separate the groups and are not pointers."
)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report, write nothing")
    args = ap.parse_args()

    rm = load(ROOT, exclude={OUT.name})
    claimed = bytearray(len(rm.rom))
    for r in rm.regions:
        claimed[r["offset"]:r["offset"] + r["size"]] = b"\1" * r["size"]

    prg, bsz = rm.meta["prg_offset"], rm.meta["prg_bank_size"]
    regions = []

    def free(off, size):
        return not any(claimed[off:off + size])

    for bank in sorted(gfx.TABLES):
        data = rm.prg_bank(bank)
        for addr, count in gfx.TABLES[bank]:
            off = prg + bank * bsz + (addr - 0x8000)
            if not free(off, 2 * count):
                continue
            regions.append({
                "id": f"bank{bank}.gfxtbl_{addr:04X}", "offset": off, "size": 2 * count,
                "kind": "pointer_table", "name": f"Tile block pointers ({count} entries)",
                "confidence": "confirmed", "cpu_addr": addr,
                "sha1": hashlib.sha1(rm.rom[off:off + 2 * count]).hexdigest(),
                "description": TABLE_DESC.format(count=count, start=addr,
                                                 end=addr + 2 * count - 1),
            })
            claimed[off:off + 2 * count] = b"\1" * (2 * count)

        for b in gfx.blocks(data, bank):
            off = prg + bank * bsz + (b["addr"] - 0x8000)
            if not free(off, b["size"]):
                continue
            n = len(b["tiles"])
            extra = n % 16
            live = ""
            if not b["in_table"]:
                live += ("NO POINTER TABLE NAMES THIS BLOCK. It is here because the chain "
                         "from the previous block ends exactly at its first byte and it "
                         "decodes to a whole number of tiles, which is why it is a lead "
                         "and not a confirmed region. ")
            if extra:
                live += (f"This block's output is {extra} bytes over a whole number of "
                         "tiles, which is NOT explained. ")
            regions.append({
                "id": f"bank{bank}.gfx_{b['addr']:04X}", "offset": off, "size": b["size"],
                "kind": "graphics",
                "name": f"Tile block: {n // 16} tiles" + (f" + {extra} B" if extra else ""),
                "confidence": "confirmed" if b["in_table"] else "lead",
                "cpu_addr": b["addr"],
                "sha1": hashlib.sha1(rm.rom[off:off + b["size"]]).hexdigest(),
                "description": BLOCK_DESC.format(size=b["size"], out=n, tiles=n / 16,
                                                 ratio=n / b["size"], esc=b["esc"],
                                                 hdr2=b["hdr2"], live=live),
                "codec": "rle_toggle_escape",
            })
            claimed[off:off + b["size"]] = b"\1" * b["size"]

    regions.sort(key=lambda r: r["offset"])
    doc = {
        "_comment": "GENERATED by tools/gen-gfx-regions.py - do not hand-edit. The tile "
                    "blocks and the pointer tables that name them. The codec, the evidence "
                    "for it and what is not claimed are in tools/tgl/gfx.py.",
        "regions": regions,
    }
    text = json.dumps(doc, indent=2) + "\n"
    total = sum(r["size"] for r in regions)
    print(f"{len(regions)} regions, {total:,} bytes "
          f"({100 * total / len(rm.rom):.2f}% of the image)")
    if args.check:
        old = OUT.read_text() if OUT.exists() else ""
        print("no change" if old == text else "WOULD CHANGE")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
