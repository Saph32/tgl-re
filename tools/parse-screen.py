#!/usr/bin/env python3
"""Walk bank 4's per-area screen data into `annotations/regions/60-screen.json`.

    python tools/parse-screen.py            # rewrite the file, print the checks
    python tools/parse-screen.py --check    # report, write nothing
    python tools/parse-screen.py --block 3  # one entry block, record by record

**The output file is generated. A hand edit to it is lost on the next run.**

The format, the interpreter and what is NOT established are in `tools/tgl/screen.py`.

What this checks, and why the checks are worth something
--------------------------------------------------------
1. **Every block ends properly.** A block stops at command 3, which is an unconditional
   jump, or at a trigger too large to ever fire. Neither is a length I chose: the trigger
   threshold falls out of the data, which separates cleanly into 209 distinct values at
   $0791 or below and four above with a gap of 2,415 between.
2. **Triggers never decrease.** A record carries the scroll position at which the NEXT
   record fires, so within a block they should ascend - and across all 25 entry blocks and
   476 transitions, they do. This is the check that carries the operand lengths: get one
   wrong and the walk reads a trigger out of the middle of something else, which almost
   never lands above its predecessor.
3. **Nothing runs off.** The walk meets no byte that is not one of the ten commands.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tgl import screen
from tgl.model import load

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "annotations" / "regions" / "60-screen.json"

STREAM_DESC = (
    "Screen-data command stream, ${start:04X}-${end:04X}. Records are "
    "[command][operands][next trigger lo][next trigger hi], run by the interpreter at "
    "$E5BD in bank 7 and dispatched through the ten-entry table at $E6F3. The trigger is a "
    "scroll position: $E6CE compares it against the running counter $B0/$B1 every step and "
    "fires the record when they match. "
    "THE EXTENT IS WALKED, NOT ARGUED: every byte here was consumed by a record whose "
    "length came from its own handler, following command 3 and command 9 jumps as a "
    "worklist rather than reading straight through - a linear read stops at the first "
    "command 3 with live bytes still ahead of it. "
    "{blocks} block start{s} in this run; {n} records. Two checks carry it: the walk meets "
    "no byte that is not one of the ten commands, and the triggers never decrease within a "
    "block - which they would if any operand length were wrong. Generated by "
    "tools/parse-screen.py; the format is in tools/tgl/screen.py."
)

POOL_DESC = (
    "Referenced data, ${start:04X}-${end:04X}, {size} bytes. The command stream does not "
    "read these bytes; it POINTS at them. {ptrs} pointer{s} from commands 1, 2, 4, 6 and 7 "
    "land inside this run, the lowest at ${first:04X}. "
    "**THIS IS A LEAD, and the extent is the only claim.** What the blocks contain is not "
    "established, and neither is where one ends and the next begins - the pointers are "
    "dense here (the median gap between consecutive targets across the whole pool is 36 "
    "bytes) but nothing has been read that bounds an individual block. Command 6's "
    "pointers are dereferenced at $E82B, which takes two bytes through them and then treats "
    "target+2 as a stream of its own; command 4's go to $D92D. Reading either would turn "
    "this run into real regions."
)


def runs_of(covered: bytearray, lo: int, hi: int, want: int):
    out, i = [], lo
    while i < hi:
        if covered[i] == want:
            j = i
            while j < hi and covered[j] == want:
                j += 1
            out.append((i, j))
            i = j
        else:
            i += 1
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report, write nothing")
    ap.add_argument("--block", type=int, help="print one entry block, record by record")
    args = ap.parse_args()

    rm = load(ROOT, exclude={OUT.name})
    b4 = rm.prg_bank(4)
    g = screen.walk(b4)

    if args.block is not None:
        i = args.block
        p = g["pointers"][i]
        area = i + screen.FIRST_AREA
        B = lambda x: b4[x - 0x8000]
        print(f"entry {i} (area {area}) at ${p:04X}, opening trigger "
              f"${B(p) | (B(p + 1) << 8):04X}")
        a = p + 2
        while True:
            c = B(a)
            n = screen.operand_len(b4, a, area)
            if c > 9 or n is None:
                print(f"  ${a:04X}  ** ${c:02X} is not a command **")
                break
            ops = " ".join(f"{B(a + 1 + k):02X}" for k in range(n))
            trig = None if c == 3 else B(a + 1 + n) | (B(a + 2 + n) << 8)
            print(f"  ${a:04X}  {c}  {screen.COMMANDS[c][0]:<26} [{ops[:44]}]"
                  + (f"  next at ${trig:04X}" if trig is not None else "  (jump)"))
            a += 1 + n + (0 if c == 3 else screen.TRIGGER_BYTES)
            if c == 3 or (trig is not None and trig >= screen.TERMINAL_TRIGGER):
                break
        return 0

    lo, hi = screen.ENTRY_TABLE - 0x8000 + 2 * screen.ENTRY_COUNT, 0x4000
    stream = runs_of(g["covered"], lo, hi, 1)
    pool = runs_of(g["covered"], lo, hi, 0)
    got = sum(b - a for a, b in stream)
    from collections import Counter
    census = Counter(c for _, c, _ in g["records"])

    print(f"{len(g['starts'])} block starts: {screen.ENTRY_COUNT} from the table at "
          f"${screen.ENTRY_TABLE:04X}, {len(g['starts']) - screen.ENTRY_COUNT} more found "
          "by following command 3 and command 9 jumps")
    print(f"{len(g['records'])} records, {got:,} of {hi - lo:,} bytes above the table "
          f"({100 * got / (hi - lo):.1f}%)")
    print(f"{len(g['stops'])} places the walk met a byte that is not a command")
    print("command census: " + "  ".join(f"{c}:{census.get(c, 0)}" for c in range(10)))
    print(f"{len(g['pool'])} pointers into the referenced pool, "
          f"${min(g['pool']):04X}-${max(g['pool']):04X}")
    print(f"{len(stream)} stream runs, {len(pool)} pool runs "
          f"({sum(b - a for a, b in pool):,} bytes)")

    prg, bsz = rm.meta["prg_offset"], rm.meta["prg_bank_size"]
    claimed = bytearray(len(rm.rom))
    for r in rm.regions:
        claimed[r["offset"]:r["offset"] + r["size"]] = b"\1" * r["size"]
    regions = []

    def add(off0, size, rid, kind, name, desc, conf):
        off = prg + 4 * bsz + off0
        if any(claimed[off:off + size]):
            return
        regions.append({"id": rid, "offset": off, "size": size, "kind": kind, "name": name,
                        "confidence": conf, "cpu_addr": 0x8000 + off0,
                        "sha1": hashlib.sha1(rm.rom[off:off + size]).hexdigest(),
                        "description": desc})
        claimed[off:off + size] = b"\1" * size

    starts = set(g["starts"])
    for a, b in stream:
        recs = [r for r in g["records"] if a <= r[0] - 0x8000 < b]
        blocks = sum(1 for s in starts if a <= s - 0x8000 < b)
        add(a, b - a, f"bank4.screen_{0x8000 + a:04X}", "level",
            f"Screen-data stream: {len(recs)} records",
            STREAM_DESC.format(start=0x8000 + a, end=0x8000 + b - 1, blocks=blocks,
                               s="" if blocks == 1 else "s", n=len(recs)),
            "confirmed")
    poolptrs = sorted(g["pool"])
    # Other files claim structures INSIDE the pool (bank 4's spawn scripts and graphics
    # streams, tools/parse-enemies.py), so a pool run is cut around them rather than
    # dropped whole the way add() drops a run that touches a claimed byte.
    base4 = prg + 4 * bsz
    split = []
    for a, b in pool:
        s = None
        for o in range(a, b + 1):
            free = o < b and not claimed[base4 + o]
            if free and s is None:
                s = o
            elif not free and s is not None:
                split.append((s, o))
                s = None
    pool = split
    for a, b in pool:
        inside = [p for p in poolptrs if a <= p - 0x8000 < b]
        if not inside:
            add(a, b - a, f"bank4.data_{0x8000 + a:04X}", "data",
                f"Unreferenced run, {b - a} bytes",
                f"${0x8000 + a:04X}-${0x8000 + b - 1:04X}, {b - a} bytes that the command "
                "stream neither reads nor points at. NOT ESTABLISHED what these are. They "
                "sit between a block's last record and the next block, so leftover data "
                "from development is one possibility and a pointer this project has not "
                "found is another.", "lead")
            continue
        add(a, b - a, f"bank4.data_{0x8000 + a:04X}", "data",
            f"Referenced data pool, {len(inside)} pointers in",
            POOL_DESC.format(start=0x8000 + a, end=0x8000 + b - 1, size=b - a,
                             ptrs=len(inside), s="" if len(inside) == 1 else "s",
                             first=min(inside)), "lead")

    regions.sort(key=lambda r: r["offset"])
    doc = {"_comment": "GENERATED by tools/parse-screen.py - do not hand-edit. Bank 4's "
                       "per-area screen data: the command streams the interpreter walks, "
                       "and the pool they point at. Format: tools/tgl/screen.py.",
           "regions": regions}
    text = json.dumps(doc, indent=2) + "\n"
    print(f"\n{len(regions)} regions, {sum(r['size'] for r in regions):,} bytes")
    if args.check:
        print("no change" if OUT.exists() and OUT.read_text() == text else "WOULD CHANGE")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
