#!/usr/bin/env python3
"""Claim byte tables that their own readers bound, into `annotations/regions/75-tables.json`.

    python tools/find-tables.py          # rewrite the file, print what was found
    python tools/find-tables.py --check  # report, write nothing
    python tools/find-tables.py --list   # every candidate, largest first

**The output file is generated. A hand edit to it is lost on the next run.**

The rule, and why it is a bound rather than a guess
---------------------------------------------------
When one routine reads two tables with the same index register, **the distance between
their base addresses is the length of the earlier one**. Bank 7 `$CFAB`-`$CFBD` is the
clearest case: four `LDA abs,Y` six bytes apart, reading `$D02C`, `$D0AB`, `$D12A` and
`$D1A9` - so the first three are 127 entries each, stated by the code and needing no
argument about the bytes.

**The "same routine" part is the whole rule.** Two bases read by unrelated code bound
nothing, so a candidate is only taken when the two reads are within 24 bytes of each other.
Without that, the nearest base anywhere in the bank looks like a bound and the answer is
worthless - an earlier version of this scan "bounded" bank 5 `$B30C` at 3,315 bytes, which
is simply the rest of the gap.

What this does NOT do
---------------------
A SECOND, WEAKER RULE runs after it: a gap whose first byte is a read base and whose end is
claimed is taken as a table to the next base or the gap's end. Those regions are marked
`lead`, because their extent comes from the neighbours rather than the reader.

It claims extents, not meanings. A region from here says "these bytes are a table this many
entries long, read by that instruction" and nothing else, unless it appears in `NOTES`
below. It also cannot see the last table in a group - nothing bounds it from the right - so
those are left unclaimed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tgl import disasm
from tgl.model import load

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "annotations" / "regions" / "75-tables.json"

NEAR = 24        # how close two reads must be to count as the same routine
MIN_LEN = 4

# Tables whose meaning is established elsewhere get their own words. Everything else gets
# the generic description, which claims the extent and says so.
NOTES = {
    (7, 0xC28D): ("Metasprite pointers, low bytes",
                  "The low half of the split pointer table an object's $0548,X indexes. "
                  "The high half begins at $C319, which is why this half measures 140 - and "
                  "the halves OVERLAP by that one byte, because $C28D + 140 is $C319 and "
                  "high[0] is never read. See tools/tgl/metasprite.py."),
    (7, 0xC319): ("Metasprite pointers, high bytes",
                  "The high half of the metasprite pointer table, 141 entries, ending "
                  "exactly where the first metasprite record begins at $C3A6. Its first "
                  "byte is also low[140] of the table below it."),
    (6, 0x80DE): ("Object dispatch, low bytes",
                  "The low half of bank 6's object behaviour table, indexed by the object "
                  "type from $0500,X masked with AND #$7F. The high half is at $815D and "
                  "the two overlap by one byte for the same reason the metasprite table "
                  "does."),
    (6, 0x815D): ("Object dispatch, high bytes",
                  "The high half of bank 6's object behaviour table. $821E pushes this "
                  "byte, then $80DE,Y, then RTSes - so the entries are targets minus one."),
}

GENERIC = (
    "A table of {n} bytes at ${addr:04X}, read by {reader} at ${ra:04X}. "
    "THE EXTENT COMES FROM THE CODE, not from the data: the same routine reads another "
    "table based at ${nxt:04X} from ${pair:04X}, {near} bytes away in the instruction "
    "stream, so this table runs exactly up to that base. Two bases read by unrelated code "
    "would bound nothing, which is why the reads have to be neighbours. "
    "**WHAT THE BYTES MEAN IS NOT ESTABLISHED** - this region claims the extent and the "
    "reader and stops there. Generated by tools/find-tables.py."
)


def candidates(rm):
    prg, bsz = rm.meta["prg_offset"], rm.meta["prg_bank_size"]
    claimed = bytearray(len(rm.rom))
    for r in rm.regions:
        claimed[r["offset"]:r["offset"] + r["size"]] = b"\1" * r["size"]

    reads = defaultdict(set)
    for r in rm.regions:
        if r["kind"] != "code":
            continue
        b = r["prg_bank"]
        d = rm.prg_bank(b)
        o = r["offset"] - prg - b * bsz
        a = r["cpu_addr"]
        end = o + r["size"]
        while o < end:
            ins = disasm.decode(d, o, a)
            if ins.mnemonic == "TRUNC":
                break
            if ins.mode in ("abx", "aby") and ins.operand and ins.operand >= 0x8000:
                reads[b].add((ins.operand, a, ins.mnemonic + " " + ins.mode))
            o += ins.size
            a += ins.size

    candidates.reads = reads
    out = []
    for b in sorted(reads):
        base = 0xC000 if b == 7 else 0x8000
        ops = sorted({op for op, _, _ in reads[b]})
        for i, op in enumerate(ops):
            # Sorted: reads[b] is a set of tuples holding strings, whose iteration order
            # changes with hash randomisation - unsorted, the output differed run to run.
            mine = sorted((a, m) for o2, a, m in reads[b] if o2 == op)
            nxt = pair = None
            for op2 in ops[i + 1:]:
                for a2, _ in sorted((a, m) for o2, a, m in reads[b] if o2 == op2):
                    if any(abs(a2 - a) <= NEAR for a, _ in mine):
                        nxt, pair = op2, a2
                        break
                if nxt:
                    break
            if nxt is None:
                continue
            n = nxt - op
            off = prg + b * bsz + (op - base)
            if n < MIN_LEN or any(claimed[off:off + n]):
                continue
            ra, mn = sorted(mine)[0]
            out.append({"bank": b, "addr": op, "n": n, "reader": ra, "mn": mn,
                        "nxt": nxt, "pair": pair, "off": off})
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    rm = load(ROOT, exclude={OUT.name})
    cs = candidates(rm)
    cs.sort(key=lambda c: (c["bank"], c["addr"]))
    # A candidate whose bytes contain another candidate's base is too long: that base ends
    # it. Two tables read with the same index and eight bytes apart are parallel fields of
    # an eight-entry record, not a 36-byte table with another one inside it.
    for i, c in enumerate(cs):
        for d2 in cs[i + 1:]:
            if d2["bank"] != c["bank"]:
                break
            if c["addr"] < d2["addr"] < c["addr"] + c["n"]:
                c["n"] = d2["addr"] - c["addr"]
                c["nxt"], c["pair"] = d2["addr"], d2["reader"]
                break
    cs = [c for c in cs if c["n"] >= MIN_LEN]
    # SECOND, WEAKER RULE - structural extents. A gap whose FIRST byte is the base of an
    # absolute-indexed read, with claimed bytes (almost always code) at its end, is taken
    # as a table from that base to the next read base inside the gap, or to the gap's end.
    # That is the "last table in a group" the reader rule cannot bound. The extent rests on
    # the surrounding claims, not on the reader, so these are LEADS and say so.
    prg, bsz = rm.meta["prg_offset"], rm.meta["prg_bank_size"]
    claimed = bytearray(len(rm.rom))
    for r in rm.regions:
        claimed[r["offset"]:r["offset"] + r["size"]] = b"" * r["size"]
    for c in cs:
        claimed[c["off"]:c["off"] + c["n"]] = b"" * c["n"]
    weak = []
    for b, rs in sorted(candidates.reads.items()):
        base = 0xC000 if b == 7 else 0x8000
        bases = sorted({op for op, _, _ in rs})
        for op in bases:
            off = prg + b * bsz + (op - base)
            if claimed[off] or not claimed[off - 1]:
                continue
            e = off
            while e < prg + (b + 1) * bsz and not claimed[e]:
                e += 1
            nxt = [x for x in bases if op < x < op + (e - off)]
            n = (nxt[0] - op) if nxt else e - off
            if n < 1 or n > 256:
                continue
            ra, mn = sorted((a, m) for o2, a, m in rs if o2 == op)[0]
            weak.append({"bank": b, "addr": op, "n": n, "reader": ra, "mn": mn, "off": off,
                         "why": f"next read base ${nxt[0]:04X}" if nxt else
                                f"the claimed byte at ${op + n:04X}"})
            claimed[off:off + n] = b"" * n
    print(f"{len(cs)} tables bounded by their own readers, "
          f"{sum(c['n'] for c in cs):,} bytes")
    named = sum(1 for c in cs if (c["bank"], c["addr"]) in NOTES)
    print(f"{named} of them have an established meaning; the rest claim extent only")

    if args.list:
        for c in sorted(cs, key=lambda c: -c["n"]):
            tag = NOTES.get((c["bank"], c["addr"]), ("", ""))[0]
            print(f"  bank {c['bank']} ${c['addr']:04X}  {c['n']:5d} B  read by "
                  f"${c['reader']:04X}  bounded by ${c['pair']:04X}   {tag}")

    regions = []
    for c in cs:
        key = (c["bank"], c["addr"])
        if key in NOTES:
            name, desc = NOTES[key]
            desc += (f" Extent: {c['n']} bytes, bounded by the base at ${c['nxt']:04X} read "
                     f"from ${c['pair']:04X}.")
        else:
            name = f"Table, {c['n']} bytes"
            desc = GENERIC.format(n=c["n"], addr=c["addr"], reader=c["mn"], ra=c["reader"],
                                  nxt=c["nxt"], pair=c["pair"],
                                  near=abs(c["pair"] - c["reader"]))
        regions.append({
            "id": f"bank{c['bank']}.tbl_{c['addr']:04X}", "offset": c["off"], "size": c["n"],
            "kind": "pointer_table" if key in NOTES else "data", "name": name,
            "confidence": "confirmed", "cpu_addr": c["addr"],
            "sha1": hashlib.sha1(rm.rom[c["off"]:c["off"] + c["n"]]).hexdigest(),
            "description": desc})

    for w in weak:
        regions.append({
            "id": f"bank{w['bank']}.tbl_{w['addr']:04X}", "offset": w["off"], "size": w["n"],
            "kind": "data", "name": f"Table, {w['n']} bytes (structural extent)",
            "confidence": "lead", "cpu_addr": w["addr"],
            "sha1": hashlib.sha1(rm.rom[w["off"]:w["off"] + w["n"]]).hexdigest(),
            "description": f"A table read by {w['mn']} at ${w['reader']:04X}, starting at the "
                           "first byte of an unclaimed stretch. ITS EXTENT IS STRUCTURAL, NOT "
                           f"STATED BY THE CODE: it runs to {w['why']}, because nothing else "
                           "claims the bytes in between. A LEAD - the reader's index range has "
                           "not been checked. Generated by tools/find-tables.py (second rule)."})
    print(f"{len(weak)} more by the weaker structural rule, "
          f"{sum(w['n'] for w in weak):,} bytes, all leads")

    regions.sort(key=lambda r: r["offset"])
    doc = {"_comment": "GENERATED by tools/find-tables.py - do not hand-edit. Byte tables "
                       "whose extent is fixed by the distance between two bases the same "
                       "routine reads.",
           "regions": regions}
    text = json.dumps(doc, indent=2) + "\n"
    print(f"{len(regions)} regions, {sum(r['size'] for r in regions):,} bytes")
    if args.check:
        print("no change" if OUT.exists() and OUT.read_text() == text else "WOULD CHANGE")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
